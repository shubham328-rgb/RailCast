const CRUISE = { Rajdhani: 90, Superfast: 75, Express: 60, Passenger: 42 }; // km/h effective
const HALT_BY_TYPE = { Rajdhani: [2,3,5], Superfast: [1,2,2,3,5], Express: [1,2,2,3,5,10], Passenger: [1,1,2,2,3] };

function hmToMin(hm) { const [h,m] = hm.split(':').map(Number); return h*60+m; }
function minToHM(t) { t = ((t%1440)+1440)%1440; const h=Math.floor(t/60), m=t%60;
  return String(h).padStart(2,'0')+':'+String(m).padStart(2,'0'); }

/* ---- build schedules ---------------------------------------------------- */
function buildTrains() {
  const trains = {};
  for (const [no,name,type,corr,si,ei,dep] of TRAINS_SPEC) {
    const pool = CORRIDORS[corr].slice(si, ei+1);
    const km0 = pool[0][2];
    const speed = CRUISE[type];
    const stations = [];
    let clock = hmToMin(dep);            // minutes since midnight at origin dep
    for (let i = 0; i < pool.length; i++) {
      const [code,sname,kmAbs] = pool[i];
      const km = kmAbs - km0;
      let sched_arr = null, halt = 0;
      if (i > 0) {
        const gap = km - (pool[i-1][2]-km0);
        // pure run time from distance, plus schedule PADDING (recovery slack).
        // padding grows a little with distance so long sections can absorb delay.
        const pureRun = (gap / speed) * 60;
        const padFactor = 1.12 + (type === 'Passenger' ? 0.03 : 0.0) + gap/6000;
        clock += pureRun * padFactor;
        sched_arr = Math.round(clock);
        // halt (0 at terminus)
        halt = (i === pool.length-1) ? 0 : pick(HALT_BY_TYPE[type]);
        clock = sched_arr + halt;
      }
      stations.push({
        code, name: sname, seq: i+1, km: Math.round(km),
        sched_arr: sched_arr==null ? null : minToHM(sched_arr),
        sched_dep: (i === pool.length-1) ? null : minToHM(clock),
        halt_min: halt,
        _arrMin: sched_arr, _depMin: (i===pool.length-1)? null : Math.round(clock)
      });
    }
    trains[no] = { name, type, corridor: corr, dep_time: dep, stations };
  }
  return trains;
}

/* ---- per-section intrinsic difficulty (congestion baseline) ------------- */
function sectionKey(trainNo, seq) { return trainNo + ':' + seq; }
function buildSectionBaselines(trains) {
  const base = {};
  for (const no in trains) {
    const st = trains[no].stations;
    for (let i = 1; i < st.length; i++) {
      // some sections are intrinsically busier (junction approaches etc.)
      base[sectionKey(no, i+1)] = round(0.35 + 0.4*rand(), 3); // 0.35..0.75 mean congestion
    }
  }
  return base;
}

/* ---- date helpers ------------------------------------------------------- */
function dateStr(d) { return d.toISOString().slice(0,10); }
function epochOf(dateISO, minOfDay) {
  // treat schedule times as IST wall-clock; store as unix seconds (UTC-ish).
  // minOfDay may exceed 1440 for overnight trains -> add days.
  const base = Date.parse(dateISO + 'T00:00:00+05:30') / 1000;
  return Math.round(base + minOfDay*60);
}

/* ---- the generative delay process --------------------------------------
 * new_delay = persistence*prev
 *           + congestionCoef*congestion
 *           + precedingCoef*preceding_delay
 *           + speedCoef*speed_restriction_km
 *           + weather add + monsoon add + section intrinsic
 *           - recovery( padding, prev )       (padded sections shed delay)
 *           + right-skewed noise
 * floored at -4 (trains are rarely more than a few minutes early).
 * ------------------------------------------------------------------------ */
const TRUE = {
  persistence: 0.82, congestion: 9.0, preceding: 0.11,
  speed: 0.55, rainAdd: 5.5, fogAdd: 11.0, monsoonAdd: 3.0,
  recoveryBase: 2.2, recoveryOfDelay: 0.16, noiseMean: 3.0
};

function generateRuns(trains, sectionBase) {
  const runs = [];
  const START = new Date('2026-05-01T00:00:00Z');
  const DAYS = 96;                    // > 90 days
  for (let d = 0; d < DAYS; d++) {
    const day = new Date(START.getTime() + d*86400000);
    const dISO = dateStr(day);
    const dow = day.getUTCDay();      // 0 Sun .. 6 Sat
    const month = day.getUTCMonth()+1;
    const isMonsoon = (month >= 6 && month <= 9) ? 1 : 0;

    for (const no in trains) {
      const T = trains[no];
      const st = T.stations;
      const depHour = Math.floor(hmToMin(T.dep_time)/60);
      const isNight = (depHour >= 22 || depHour < 5) ? 1 : 0;

      // departure delay: right-skewed, a touch worse at night / weekends / monsoon
      let prevDelay = round(randexp(6) - 2 + (isMonsoon?1.5:0) + (dow===5?1.2:0) + (isNight?1.0:0));
      if (prevDelay < -3) prevDelay = -3;

      // a "preceding train" delay wanders over the day
      let precedingDelay = Math.max(0, round(randexp(8) - 3));

      for (let i = 0; i < st.length; i++) {
        const s = st[i];
        // contextual features for THIS station's approach section
        const secBase = i>0 ? sectionBase[sectionKey(no,i+1)] : 0.4;
        const congestion = i>0 ? Math.min(0.99, Math.max(0.02,
            round(secBase + 0.18*randn() + (isMonsoon?0.05:0) + (isNight? -0.03:0), 3))) : round(secBase,3);
        // occasional speed restriction (engineering / weather)
        const hasSR = rand() < (isMonsoon ? 0.16 : 0.09);
        const speedR = hasSR ? Math.round(4 + randexp(9)) : 0;
        // weather
        let weather = 'clear';
        const wr = rand();
        if (isMonsoon && wr < 0.28) weather = 'rain';
        else if (!isMonsoon && wr < 0.08) weather = 'rain';
        if (month>=12 || month<=1) { if (rand()<0.18) weather='fog'; }

        let delay;
        if (i === 0) {
          delay = prevDelay;          // departure delay at origin
        } else {
          const gapKm = s.km - st[i-1].km;
          const pureRun = (gapKm / CRUISE[T.type]) * 60;
          const schedRun = s._arrMin - st[i-1]._depMin; // includes padding
          const padSlack = Math.max(0, schedRun - pureRun);
          // recovery scales with available padding and with how much delay exists
          const recovery = TRUE.recoveryBase * (padSlack/6) + TRUE.recoveryOfDelay*Math.max(0,prevDelay)*(padSlack>2?1:0.4);
          const weatherAdd = weather==='rain'?TRUE.rainAdd : weather==='fog'?TRUE.fogAdd : 0;
          delay = TRUE.persistence*prevDelay
                + TRUE.congestion*(congestion-0.4)
                + TRUE.preceding*precedingDelay
                + TRUE.speed*speedR
                + weatherAdd
                + (isMonsoon?TRUE.monsoonAdd:0)
                + (secBase-0.4)*4               // intrinsic section difficulty
                - recovery
                + randexp(TRUE.noiseMean) - TRUE.noiseMean*0.6;
          delay = round(delay);
          if (delay < -4) delay = -4;
        }

        const arrMin = i===0 ? null : s._arrMin;
        const sched_arr_epoch = i===0 ? null : epochOf(dISO, arrMin);
        const actual_arr_epoch = i===0 ? null : epochOf(dISO, arrMin) + delay*60;

        runs.push({
          train_no: no,
          run_date: dISO,
          station_seq: s.seq,
          sched_arr_epoch,
          actual_arr_epoch,
          delay_min: delay,
          prev_station_delay_min: i===0 ? 0 : prevDelay,
          day_of_week: dow,
          month,
          section_congestion_idx: congestion,
          preceding_train_delay_min: round(precedingDelay),
          weather_flag: weather,
          speed_restriction_km: speedR
        });

        // carry state forward
        prevDelay = delay;
        // preceding train delay evolves (mean-reverting random walk)
        precedingDelay = Math.max(0, round(0.7*precedingDelay + randexp(4) - 2));
      }
    }
  }
  return runs;
}

/* ---- live trains: pick recent-ish partial runs -------------------------- */
function generateLive(trains) {
  const live = [];
  const today = '2026-08-27';
  const picks = ['12559','12301','12841','12809','12695','12931','12377','12295'];
  for (const no of picks) {
    const st = trains[no].stations;
    // report early (seq 2..~40% of route) so the timeline has several stops
    // ahead to forecast and the interval visibly narrows as the train advances.
    const lastSeq = 2 + Math.floor(rand()*Math.max(1, Math.floor(st.length*0.4)-1));
    const curDelay = Math.max(0, Math.round(randexp(14) - 4));
    const s = st[lastSeq-1];
    const reportedMin = (s._arrMin!=null? s._arrMin : hmToMin(trains[no].dep_time)) + curDelay;
    live.push({
      train_no: no,
      run_date: today,
      last_reported_station_seq: lastSeq,
      current_delay_min: curDelay,
      reported_at_epoch: epochOf(today, reportedMin)
    });
  }
  return live;
}

/* ---- strip internal fields before writing trains ------------------------ */
function cleanTrains(trains) {
  const out = {};
  for (const no in trains) {
    const t = trains[no];
    out[no] = { name: t.name, type: t.type, stations: t.stations.map(s => ({
      code: s.code, name: s.name, seq: s.seq, km: s.km,
      sched_arr: s.sched_arr, sched_dep: s.sched_dep, halt_min: s.halt_min
    }))};
  }
  return out;
}

/* ---- write both .json and .js wrappers ---------------------------------- */
function writeBoth(dir, base, obj, globalPath) {
  const json = JSON.stringify(obj);
  fs.writeFileSync(path.join(dir, base + '.json'), JSON.stringify(obj, null, base==='runs'?0:2));
  const js = `/* auto-generated by data/generate.js — do not edit by hand */\n`
    + `window.RC = window.RC || {}; RC.data = RC.data || {};\n`
    + `${globalPath} = ${json};\n`;
  fs.writeFileSync(path.join(dir, base + '.js'), js);
}

/* ---- main --------------------------------------------------------------- */
(function main() {
  const dir = __dirname;
  const trainsFull = buildTrains();
  const sectionBase = buildSectionBaselines(trainsFull);
  const runs = generateRuns(trainsFull, sectionBase);
  const live = generateLive(trainsFull);
  const trains = cleanTrains(trainsFull);

  writeBoth(dir, 'trains', trains, 'RC.data.trains');
  writeBoth(dir, 'runs', runs, 'RC.data.runs');
  writeBoth(dir, 'live', live, 'RC.data.live');

  // console summary
  const delays = runs.filter(r=>r.station_seq>1).map(r=>r.delay_min);
  const mean = delays.reduce((a,b)=>a+b,0)/delays.length;
  const sorted = delays.slice().sort((a,b)=>a-b);
  const med = sorted[Math.floor(sorted.length/2)];
  console.log(`trains: ${Object.keys(trains).length}`);
  console.log(`runs (station arrivals): ${runs.length}`);
  console.log(`live trains: ${live.length}`);
  console.log(`delay mean=${mean.toFixed(2)}  median=${med}  max=${sorted[sorted.length-1]}  (mean>median => right-skew ✓)`);
})();
