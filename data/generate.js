/* ---- deterministic RNG so the dataset is reproducible ------------------- */
let _seed = 0x1a2b3c4d;
function rand() {
  // xorshift32
  _seed ^= _seed << 13; _seed ^= _seed >>> 17; _seed ^= _seed << 5;
  return ((_seed >>> 0) % 1e9) / 1e9;
}
function randn() {                 // standard normal via Box-Muller
  let u = 0, v = 0;
  while (u === 0) u = rand();
  while (v === 0) v = rand();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}
function randexp(mean) {            // exponential -> right skew
  return -mean * Math.log(1 - rand());
}
function pick(arr) { return arr[Math.floor(rand() * arr.length)]; }
function round(x, d = 0) { const p = Math.pow(10, d); return Math.round(x * p) / p; }

