#!/usr/bin/env node
/* ============================================================================
 * RailCast — synthetic data generator  (DEVELOPMENT TOOL, not shipped runtime)
 * ----------------------------------------------------------------------------
 * Produces realistic historical run data for Indian Railways coaching trains.
 *
 * This is the ONLY Node script in the project and it is NOT part of the app.
 * The app itself fits the model in the browser from the emitted data files.
 * Run once:   node data/generate.js
 *
 * Emits, into ./data/ :
 *   trains.json / trains.js   train metadata + full schedules
 *   runs.json   / runs.js     one record per station arrival, 90+ days
 *   live.json   / live.js     simulated currently-running trains
 *
 * The .json files match the schemas in the brief and exist for inspection.
 * The .js files are thin wrappers (RC.data.* = ...) loaded by the app via
 * classic <script> tags, so the whole thing runs from file:// in every
 * browser with zero network requests. See README for why.
 *
 * STATISTICAL DESIGN
 * ------------------
 * Delays are generated by an explicit generative process so that the OLS
 * model has real structure to recover, while still showing the messy
 * character of real railway data:
 *   - right-skewed delays          (exponential noise, floored near zero)
 *   - delay propagation            (persistence term carries delay forward)
 *   - recovery via schedule padding (padded sections shed delay)
 *   - section-level congestion      (per-section intrinsic difficulty)
 *   - preceding-train interference, speed restrictions, weather, monsoon
 * The "true" coefficients below are what an honest OLS fit should approximately
 * recover; we never feed them to the app.
 * ========================================================================== */
